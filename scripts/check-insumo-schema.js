require('dotenv').config({ path: '.env.local' })
const { Pool } = require('pg')
const pool = new Pool({ host: process.env.DB_HOST, port: 5432, database: process.env.DB_NAME, user: process.env.DB_USER, password: process.env.DB_PASSWORD, ssl: { rejectUnauthorized: false } })
pool.connect().then(async client => {
  await client.query('SET search_path TO "tenant_zaghi_massas_caseiras", public')
  const r = await client.query("SELECT column_name, data_type FROM information_schema.columns WHERE table_name = 't_insumo' ORDER BY ordinal_position")
  console.log('Colunas t_insumo:', r.rows.map(r => r.column_name))
  const r2 = await client.query('SELECT COUNT(*) FROM t_insumo')
  console.log('Total insumos:', r2.rows[0].count)
  client.release(); pool.end()
}).catch(err => { console.error(err.message); process.exit(1) })