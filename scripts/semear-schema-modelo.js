// scripts/semear-schema-modelo.js
//
// POPULA O tenant_modelo COM O MÍNIMO PARA UM CLIENTE NOVO OPERAR.
//
// Passo 3 do plano em docs/provisionamento.md. Sem isso, a empresa nova nasce
// com as combobox vazias e trava na primeira venda: não há forma de pagamento
// para escolher, não há tipo de entrega, e não há perfil para dar ao segundo
// usuário.
//
// A ORIGEM É A ZAGHI, SOMENTE LEITURA. São valores que já provaram funcionar em
// operação real — melhor que uma lista inventada aqui.
//
// ─── O QUE NÃO ENTRA NA SEMENTE, E POR QUÊ ──────────────────────────────────
//
// t_configuracoes_tenant fica de fora de propósito. Ela guarda nome fantasia,
// CNPJ, endereço e logo — copiar a linha da Zaghi plantaria os dados deles
// dentro de todo cliente novo. Essa linha é criada pelo provisionamento, já com
// o nome da empresa que está sendo aberta.
//
// Produto, cliente e fornecedor também ficam de fora: são dados do negócio, não
// configuração. Cliente novo começa com cadastro limpo.
//
// ─── A ARMADILHA DO ID EXPLÍCITO ────────────────────────────────────────────
//
// A cópia preserva os ids originais, porque t_dominio_valor referencia
// t_dominio por id e a FK precisa fechar. As colunas do modelo são
// `GENERATED BY DEFAULT AS IDENTITY`, que aceita id explícito — mas o contador
// interno não avança sozinho ao receber um.
//
// Sem corrigir, o primeiro INSERT normal do cliente tentaria o id 1, que já
// existe, e levaria violação de chave primária. Por isso o RESTART no fim.
//
//   node scripts/semear-schema-modelo.js            (mostra o que copiaria)
//   node scripts/semear-schema-modelo.js --aplicar  (grava)
require('dotenv').config({ path: '.env.local' })
const { Pool } = require('pg')

const APLICAR = process.argv.includes('--aplicar')

const ORIGEM  = process.env.SCHEMA_ORIGEM || 'tenant_zaghi_massas_caseiras'
const DESTINO = 'tenant_modelo'

// Ordem importa: t_dominio antes de t_dominio_valor, por causa da FK.
const SEMENTE = [
  { tabela: 't_perfil_acesso',  pk: 'perfil_id',      rotulo: 'nome' },
  { tabela: 't_dominio',        pk: 'dominio_id',     rotulo: 'nome' },
  { tabela: 't_dominio_valor',  pk: 'valor_id',       rotulo: 'valor' },
  { tabela: 't_forma_pagamento',pk: 'forma_id',       rotulo: 'nome' },
]

// DOMÍNIOS QUE ENTRAM VAZIOS.
//
// O domínio existe — a tela de Cadastros → Domínios mostra ele e o cliente
// cadastra os próprios valores. O que não vem junto é a lista da Zaghi.
//
// "Tipos de Produto" na Zaghi é Massa, Molho, Acompanhamento, Bebida. Isso é a
// fábrica de massas deles, não uma classificação de mercado. Uma padaria
// abrindo o sistema não deveria encontrar isso escrito.
//
// Os outros sete continuam populados porque são universais: unidade de medida,
// categoria de despesa, tipo de entrega, pessoa física e jurídica. Fazer o
// cliente redigitar "kg, g, l, ml" seria trabalho sem ganho nenhum.
const DOMINIOS_VAZIOS = ['Tipos de Produto']

function conexao() {
  if (process.env.DATABASE_URL) return { connectionString: process.env.DATABASE_URL }
  const host = process.env.DB_HOST
  if (!host) throw new Error('Defina DATABASE_URL ou DB_HOST/... no .env.local')
  const local = /^(localhost|127\.0\.0\.1)$/.test(host)
  return {
    host,
    port:     Number(process.env.DB_PORT ?? 5432),
    database: process.env.DB_NAME,
    user:     process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    ssl:      local ? false : { rejectUnauthorized: false },
  }
}

/** Descobre o nome real da PK — os nomes variam de tabela para tabela. */
async function pkDe(c, schema, tabela, palpite) {
  const r = await c.query(`
    SELECT a.attname
      FROM pg_index i
      JOIN pg_class cl     ON cl.oid = i.indrelid
      JOIN pg_namespace ns ON ns.oid = cl.relnamespace
      JOIN pg_attribute a  ON a.attrelid = cl.oid AND a.attnum = ANY(i.indkey)
     WHERE ns.nspname = $1 AND cl.relname = $2 AND i.indisprimary
     LIMIT 1
  `, [schema, tabela])
  return r.rows[0]?.attname ?? palpite
}

async function main() {
  const pool = new Pool(conexao())
  const c    = await pool.connect()

  try {
    console.log(APLICAR ? '\n>>> MODO GRAVACAO\n' : '\n>>> SIMULACAO — nada sera gravado. Use --aplicar.\n')
    console.log(`origem:  ${ORIGEM}  (somente leitura)`)
    console.log(`destino: ${DESTINO}\n`)

    const existe = await c.query(
      `SELECT 1 FROM information_schema.schemata WHERE schema_name = $1`, [DESTINO])
    if (existe.rows.length === 0) {
      throw new Error(`"${DESTINO}" nao existe. Rode antes: node scripts/criar-schema-modelo.js --aplicar`)
    }

    if (APLICAR) await c.query('BEGIN')

    try {
      for (const item of SEMENTE) {
        const { tabela, rotulo } = item

        const temTabela = await c.query(
          `SELECT to_regclass($1) IS NOT NULL AS existe`, [`"${ORIGEM}".${tabela}`])
        if (!temTabela.rows[0].existe) {
          console.log(`\n${tabela}: nao existe na origem. Pulando.`)
          continue
        }

        // Só o que está ativo. Perfil desativado na Zaghi (Comanda, Delivery)
        // não deve renascer ligado em cliente nenhum.
        //
        // Em t_dominio_valor entra também o recorte por domínio: os valores dos
        // domínios listados em DOMINIOS_VAZIOS ficam de fora.
        const filtro = tabela === 't_dominio_valor'
          ? `WHERE v.active_flg = true AND d.nome <> ALL($1::text[])`
          : `WHERE active_flg = true`

        const consulta = tabela === 't_dominio_valor'
          ? `SELECT v.* FROM "${ORIGEM}".t_dominio_valor v
               JOIN "${ORIGEM}".t_dominio d ON d.dominio_id = v.dominio_id
             ${filtro} ORDER BY v.valor_id`
          : `SELECT * FROM "${ORIGEM}"."${tabela}" ${filtro} ORDER BY 1`

        const params = tabela === 't_dominio_valor' ? [DOMINIOS_VAZIOS] : []
        const linhas = await c.query(consulta, params)

        const jaTem = await c.query(`SELECT COUNT(*)::int AS n FROM "${DESTINO}"."${tabela}"`)

        console.log(`\n${tabela} — ${linhas.rows.length} linha(s) na origem, ${jaTem.rows[0].n} no modelo`)

        if (jaTem.rows[0].n > 0) {
          console.log('  Modelo ja tem conteudo aqui. Pulando para nao duplicar.')
          continue
        }

        for (const r of linhas.rows) {
          const label = r[rotulo] ?? Object.values(r)[1]
          console.log(`     ${label}`)
        }

        if (!APLICAR) continue

        // INSERT ... SELECT preserva ids e funciona porque as duas tabelas têm
        // a mesma estrutura — o modelo saiu de um LIKE da origem. A consulta é
        // a mesma da simulação, então o que foi listado é o que é gravado.
        const ins = await c.query(
          `INSERT INTO "${DESTINO}"."${tabela}" ${consulta}`, params)
        console.log(`  ${ins.rowCount} linha(s) copiada(s)`)

        // TAXA DE CARTÃO NÃO SE HERDA.
        //
        // O nome da forma de pagamento serve para qualquer empresa; o
        // percentual vem do contrato de maquininha de cada uma. Herdado em
        // silêncio, entraria no cálculo de margem do cliente novo com o número
        // da Zaghi, e ninguém desconfiaria — é o tipo de erro que só aparece
        // quando alguém compara o DRE com o extrato da adquirente.
        if (tabela === 't_forma_pagamento') {
          const z = await c.query(`UPDATE "${DESTINO}"."${tabela}" SET taxa = 0 WHERE taxa <> 0`)
          console.log(`  ${z.rowCount} taxa(s) zerada(s) — cada cliente informa a sua`)
        }
      }

      // ── Reposiciona os contadores de IDENTITY ────────────────────────────
      if (APLICAR) {
        console.log('')
        for (const item of SEMENTE) {
          const pk = await pkDe(c, DESTINO, item.tabela, item.pk)
          const max = await c.query(
            `SELECT COALESCE(MAX("${pk}"), 0)::int AS m FROM "${DESTINO}"."${item.tabela}"`)
          const proximo = max.rows[0].m + 1
          await c.query(
            `ALTER TABLE "${DESTINO}"."${item.tabela}" ALTER COLUMN "${pk}" RESTART WITH ${proximo}`)
          console.log(`  ${item.tabela}.${pk} — proximo id: ${proximo}`)
        }
        await c.query('COMMIT')
        console.log('\nOK — semente aplicada ao modelo.')
      } else {
        console.log('\nNenhuma linha foi gravada. Rode com --aplicar.')
      }
    } catch (e) {
      if (APLICAR) await c.query('ROLLBACK')
      throw e
    }
  } finally {
    c.release()
    await pool.end()
  }
}

main().catch(err => { console.error('\nERRO:', err.message); process.exit(1) })
