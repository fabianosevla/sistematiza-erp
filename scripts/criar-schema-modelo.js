// scripts/criar-schema-modelo.js
//
// CRIA O SCHEMA-MODELO A PARTIR DE UM TENANT EXISTENTE. ESTRUTURA, SEM DADOS.
//
// Passo 2 do plano em docs/provisionamento.md. O `tenant_modelo` passa a ser a
// origem de todo cliente novo — é ele que o provisionamento clona.
//
// O SCHEMA DE ORIGEM NUNCA É ESCRITO. Todas as alterações acontecem no destino.
// A Zaghi é lida e nada mais.
//
// ─── POR QUE CLONAR DO BANCO E NÃO GERAR DO DRIZZLE ─────────────────────────
//
// O levantamento (check-estrutura-tenant.js) achou 63 tabelas no banco contra
// 56 declaradas no Drizzle. As sete de diferença incluem t_compra e
// t_compra_item — Compra Rápida inteira — e t_producao_grade e
// t_producao_registro, que são a grade de produção. Gerar do Drizzle entregaria
// um cliente sem compras e sem produção.
//
// ─── O QUE O `LIKE` RESOLVE E O QUE NÃO ─────────────────────────────────────
//
// `CREATE TABLE ... (LIKE origem INCLUDING ALL)` traz tipo, default, NOT NULL,
// chave primária, índice e check constraint. Não traz foreign key — e trata
// mal coluna `serial`, que é o caso de todas as 63 chaves deste banco.
//
// Coluna `serial` tem default `nextval('schema_origem.tabela_col_seq')`, com o
// schema no nome. O LIKE copia esse texto literal, e o schema novo passaria a
// consumir a numeração do original. Não daria erro: daria dois clientes
// dividindo a mesma sequência, e todo INSERT quebrando no dia em que a origem
// fosse apagada.
//
// A solução aplicada aqui é converter as colunas do MODELO para
// `GENERATED BY DEFAULT AS IDENTITY`. Identity é tratado nativamente pelo LIKE:
// cada clone ganha sequence própria, sem script nenhum. Conserta-se uma vez, e
// nenhum cliente futuro corre o risco.
//
// `BY DEFAULT` e não `ALWAYS` de propósito: permite INSERT com id explícito,
// que é o que scripts de carga e correção fazem.
//
// A Zaghi continua com `serial` e passa a diferir do modelo nesse detalhe.
// É diferença de mecanismo, não de comportamento: as duas numeram sozinhas.
//
//   node scripts/criar-schema-modelo.js                (simula)
//   node scripts/criar-schema-modelo.js --aplicar      (grava)
//   node scripts/criar-schema-modelo.js --aplicar --recriar   (derruba antes)
require('dotenv').config({ path: '.env.local' })
const { Pool } = require('pg')

const APLICAR = process.argv.includes('--aplicar')
const RECRIAR = process.argv.includes('--recriar')

const ORIGEM  = process.env.SCHEMA_ORIGEM  || 'tenant_zaghi_massas_caseiras'
const DESTINO = 'tenant_modelo'

function conexao() {
  if (process.env.DATABASE_URL) return { connectionString: process.env.DATABASE_URL }
  const host = process.env.DB_HOST
  if (!host) throw new Error('Defina DATABASE_URL ou DB_HOST/... no .env.local')
  const local = /^(localhost|127\.0\.0\.1)$/.test(host)
  return {
    host,
    port:     Number(process.env.DB_PORT ?? 5432),
    database: process.env.DB_NAME,
    user:     process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    ssl:      local ? false : { rejectUnauthorized: false },
  }
}

async function main() {
  const pool = new Pool(conexao())
  const c    = await pool.connect()

  try {
    console.log(APLICAR ? '\n>>> MODO GRAVACAO\n' : '\n>>> SIMULACAO — nada sera gravado. Use --aplicar.\n')
    console.log(`origem:  ${ORIGEM}  (somente leitura)`)
    console.log(`destino: ${DESTINO}\n`)

    // ── Origem existe? ───────────────────────────────────────────────────────
    const ok = await c.query(
      `SELECT 1 FROM information_schema.schemata WHERE schema_name = $1`, [ORIGEM])
    if (ok.rows.length === 0) throw new Error(`Schema de origem "${ORIGEM}" nao existe.`)

    // ── Destino já existe? ───────────────────────────────────────────────────
    const jaTem = await c.query(
      `SELECT 1 FROM information_schema.schemata WHERE schema_name = $1`, [DESTINO])
    if (jaTem.rows.length > 0 && !RECRIAR) {
      console.log(`"${DESTINO}" ja existe. Use --recriar para derruba-lo e refazer.`)
      return
    }

    // Trava: o destino é fixo no código e nunca pode ser um tenant registrado.
    // Script de estrutura que aceita nome por argumento é script que uma hora
    // apaga o schema de um cliente.
    const eTenant = await c.query(
      `SELECT 1 FROM public.t_tenant WHERE schema_name = $1`, [DESTINO])
    if (eTenant.rows.length > 0) {
      throw new Error(`"${DESTINO}" pertence a um tenant registrado. Abortando.`)
    }

    // ── O que será copiado ───────────────────────────────────────────────────
    const tabelas = (await c.query(`
      SELECT table_name FROM information_schema.tables
       WHERE table_schema = $1 AND table_type = 'BASE TABLE'
       ORDER BY table_name
    `, [ORIGEM])).rows.map(r => r.table_name)

    const seriais = (await c.query(`
      SELECT table_name, column_name, is_nullable
        FROM information_schema.columns
       WHERE table_schema = $1 AND column_default LIKE 'nextval%'
       ORDER BY table_name, column_name
    `, [ORIGEM])).rows

    const fks = (await c.query(`
      SELECT cl.relname AS tabela, con.conname AS nome,
             pg_get_constraintdef(con.oid) AS definicao
        FROM pg_constraint con
        JOIN pg_class cl     ON cl.oid = con.conrelid
        JOIN pg_namespace ns ON ns.oid = cl.relnamespace
       WHERE ns.nspname = $1 AND con.contype = 'f'
    `, [ORIGEM])).rows

    console.log(`${tabelas.length} tabela(s) · ${seriais.length} coluna(s) serial · ${fks.length} foreign key(s)\n`)

    if (!APLICAR) {
      console.log('Seria feito, nesta ordem:')
      console.log(`  1. ${jaTem.rows.length > 0 ? 'DROP SCHEMA + ' : ''}CREATE SCHEMA ${DESTINO}`)
      console.log(`  2. ${tabelas.length} CREATE TABLE ... (LIKE ${ORIGEM}.x INCLUDING ALL)`)
      console.log(`  3. ${seriais.length} coluna(s) convertida(s) de serial para IDENTITY`)
      console.log(`  4. ${fks.length} foreign key(s) recriada(s) apontando para ${DESTINO}`)
      console.log('\nNenhum dado e copiado. A semente e um passo separado.')
      console.log('Rode com --aplicar para gravar.')
      return
    }

    await c.query('BEGIN')
    try {
      // 1. Schema
      if (jaTem.rows.length > 0) {
        await c.query(`DROP SCHEMA "${DESTINO}" CASCADE`)
        console.log(`  DROP SCHEMA ${DESTINO}`)
      }
      await c.query(`CREATE SCHEMA "${DESTINO}"`)
      console.log(`  CREATE SCHEMA ${DESTINO}`)

      // 2. Tabelas
      for (const t of tabelas) {
        await c.query(
          `CREATE TABLE "${DESTINO}"."${t}" (LIKE "${ORIGEM}"."${t}" INCLUDING ALL)`)
      }
      console.log(`  ${tabelas.length} tabela(s) criada(s)`)

      // 3. serial → IDENTITY
      //
      // O DROP DEFAULT vem antes e é obrigatório: o default copiado pelo LIKE
      // ainda aponta para a sequence da origem, e ADD GENERATED recusa coluna
      // que já tem default.
      let convertidas = 0
      for (const s of seriais) {
        const tab = `"${DESTINO}"."${s.table_name}"`
        const col = `"${s.column_name}"`
        await c.query(`ALTER TABLE ${tab} ALTER COLUMN ${col} DROP DEFAULT`)
        // IDENTITY exige NOT NULL. Chave primária já é, mas serial em coluna
        // comum pode não ser — e aí o ALTER falharia no meio do lote.
        if (s.is_nullable === 'YES') {
          await c.query(`ALTER TABLE ${tab} ALTER COLUMN ${col} SET NOT NULL`)
        }
        await c.query(`ALTER TABLE ${tab} ALTER COLUMN ${col} ADD GENERATED BY DEFAULT AS IDENTITY`)
        convertidas++
      }
      console.log(`  ${convertidas} coluna(s) convertida(s) para IDENTITY`)

      // 4. Foreign keys
      //
      // pg_get_constraintdef devolve a definicao com o schema de origem no
      // REFERENCES. Trocar pelo destino e o que faz a FK apontar para dentro do
      // modelo, e nao de volta para a Zaghi.
      for (const fk of fks) {
        const def = fk.definicao.replaceAll(`${ORIGEM}.`, `"${DESTINO}".`)
        await c.query(
          `ALTER TABLE "${DESTINO}"."${fk.tabela}" ADD CONSTRAINT "${fk.nome}" ${def}`)
        console.log(`  FK ${fk.tabela}.${fk.nome}`)
      }

      await c.query('COMMIT')
      console.log(`\nOK — ${DESTINO} criado com estrutura, sem dados.`)
      console.log('Proximo passo: a semente (perfis, dominios, formas de pagamento).')
    } catch (e) {
      await c.query('ROLLBACK')
      throw e
    }

    // ── Conferência: o modelo bate com a origem? ─────────────────────────────
    const conf = await c.query(`
      SELECT
        (SELECT COUNT(*) FROM information_schema.tables
          WHERE table_schema = $1 AND table_type = 'BASE TABLE')::int AS origem,
        (SELECT COUNT(*) FROM information_schema.tables
          WHERE table_schema = $2 AND table_type = 'BASE TABLE')::int AS destino
    `, [ORIGEM, DESTINO])
    const { origem, destino } = conf.rows[0]
    console.log(`\nConferencia de tabelas — origem ${origem} · modelo ${destino}${origem === destino ? ' · OK' : ' · DIVERGENTE'}`)

    const restou = await c.query(`
      SELECT COUNT(*)::int AS n FROM information_schema.columns
       WHERE table_schema = $1 AND column_default LIKE 'nextval%'
    `, [DESTINO])
    console.log(`Colunas ainda apontando para sequence externa: ${restou.rows[0].n}${restou.rows[0].n === 0 ? ' · OK' : ' · PROBLEMA'}`)
  } finally {
    c.release()
    await pool.end()
  }
}

main().catch(err => { console.error('\nERRO:', err.message); process.exit(1) })
